// Official Rust toolchain, pinned in rust-toolchain.toml. No third-party crates.
import {execFileSync} from 'node:child_process';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
execFileSync('cargo',['build','--manifest-path','rust/Cargo.toml','--release','--target','wasm32-unknown-unknown','--locked'],{cwd:root,stdio:'inherit'});
const bytes=await readFile(new URL('../rust/target/wasm32-unknown-unknown/release/crownfold_tactics.wasm',import.meta.url));
const hash=createHash('sha256').update(bytes).digest('hex');
const source=`// Generated by npm run build:rust. Do not edit.\n// SHA-256: ${hash}\nexport const WASM_BASE64='${bytes.toString('base64')}';\nexport const WASM_SHA256='${hash}';\n`;
const output=new URL('../src/rust-tactics-data.mjs',import.meta.url);
if(process.argv.includes('--check')){
  if(await readFile(output,'utf8')!==source)throw new Error('Committed Rust/Wasm is stale; run npm run build:rust');
  console.log(`Verified Rust/Wasm ${hash} (${bytes.length} bytes)`);
}else {await writeFile(output,source);console.log(`Built Rust/Wasm ${hash} (${bytes.length} bytes)`);}
